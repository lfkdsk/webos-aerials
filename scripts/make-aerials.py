#!/usr/bin/env python3
"""Generate app/aerials.js from Apple's tvOS Aerial manifest.

    curl -o resources.tar https://sylvan.apple.com/Aerials/resources-16.tar
    mkdir x && tar -xf resources.tar -C x
    python3 -I scripts/make-aerials.py x/entries.json x/TVIdleScreenStrings.bundle/zh_CN.lproj/Localizable.nocache.strings

The launcher runs from file:// and cannot fetch the manifest itself (no CORS on
sylvan.apple.com), so the list is baked in. Video URLs are plain <video> sources,
which need no CORS.
"""
import json
import os
import plistlib
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://sylvan.apple.com"
QUALITIES = ["4K-HDR", "4K-SDR", "1080-HDR", "1080-SDR", "1080-H264"]
CATEGORY_NAMES = {
    "AerialCategoryLandscapes": "landscape",
    "AerialCategoryCities": "city",
    "AerialCategorySpace": "space",
    "AerialCategoryUnderwater": "underwater",
}


def main(entries_path, strings_path):
    with open(entries_path, "rb") as f:
        manifest = json.load(f)
    with open(strings_path, "rb") as f:
        strings = plistlib.load(f)
    categories = {c["id"]: CATEGORY_NAMES.get(c.get("localizedNameKey"), "other") for c in manifest["categories"]}

    assets = []
    for a in manifest["assets"]:
        urls = {}
        for q in QUALITIES:
            u = a.get("url-" + q)
            if u and u.startswith(BASE):
                urls[q] = u[len(BASE):]
        if not urls:
            continue
        # The first point of interest is the clip's opening description.
        poi = a.get("pointsOfInterest") or {}
        first_key = poi.get("0") or (poi[sorted(poi, key=lambda k: float(k))[0]] if poi else None)
        assets.append({
            "id": a["id"],
            "name": a.get("accessibilityLabel", ""),
            "zh": strings.get(first_key, "") if first_key else "",
            "cat": categories.get((a.get("categories") or [None])[0], "other"),
            "u": urls,
        })

    out = os.path.join(HERE, "app", "aerials.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/make-aerials.py from Apple's Aerial manifest (resources-%s).\n" % manifest.get("version", "?"))
        f.write("window.AERIALS = {base: %s, assets: %s};\n" % (
            json.dumps(BASE), json.dumps(assets, ensure_ascii=False, separators=(",", ":"))))
    print("wrote %d assets to %s" % (len(assets), out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: make-aerials.py <entries.json> <zh_CN Localizable.nocache.strings>")
    main(sys.argv[1], sys.argv[2])
